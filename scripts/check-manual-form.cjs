    await page.route(/\/assets\/app\.js(?:\?.*)?$/,route=>route.fulfill({contentType:'application/javascript',body:fs.readFileSync('frontend/dist/assets/app.js','utf8')}));
    await page.route('**/demo/login',route=>route.fulfill({json:{role:'analyst'}}));
    await page.route('**/applications',route=>route.fulfill({json:[application]}));
    await page.route('**/applications/999/detail',route=>route.fulfill({json:application}));
    await page.route('**/applications/999/history',route=>route.fulfill({json:[]}));
    await page.route('**/applications/999/audit',route=>route.fulfill({json:{sources:{company:{registration_date:'2026-08-01',status:'ACTIVE',okved:'47.11'}},verification:{registration_date:'2026-08-01',checked_at:'2026-10-26T10:00:00Z',age_months:2,age_stop_triggered:true,current_company:{registration_date:'2026-08-01T00:00:00Z'},registration_matches_current_db:true}}}));
    await page.route('**/applications/999/decision',route=>{submitted=route.request().postDataJSON();return route.fulfill({json:{}})});
    await page.goto('http://127.0.0.1:8081');
    await page.locator('#company-select option').first().waitFor({state:'attached'});
    await page.locator('#login-analyst').click();
    await page.locator('[data-id="999"]').click();
    await page.locator('#manual-hint').waitFor();
    assert.deepEqual(errors,[]);
    await page.locator('#verify-data').click();
    await page.locator('#verification-result dl').waitFor();
    assert.match(await page.locator('#verification-result').innerText(),/2 полных мес\./);
    assert.match(await page.locator('#verification-result').innerText(),/2026-08-01/);
    assert(await page.locator('#manual-decision option[value="APPROVED"]').evaluate(el=>el.disabled));
    assert(await page.locator('#manual-decision option[value="COUNTER_OFFER"]').evaluate(el=>el.disabled));
    assert(await page.locator('#manual-amount').isDisabled());
    assert(await page.locator('#manual-reason').evaluate(el=>el.required));
    assert.match(await page.locator('#manual-hint').innerText(),/нет доступной суммы/);
    await page.locator('#manual-decision').selectOption('NEED_INFO');
    assert(await page.locator('#manual-reason').isDisabled());
    await page.locator('#manual-comment').fill('Need synthetic updated statements');
    await page.locator('#manual-form button').click();
    await page.waitForFunction(()=>!document.querySelector('#manual-form button')?.disabled);
    assert.equal(submitted.amount,0);assert.equal(submitted.reason_code,'');assert.equal(submitted.decision,'NEED_INFO');
    application.decision={grade:'E',recommendation:'REJECTED',limit:{amount:3000000},review_terms:{amount:2000000},manual_review_triggers:['MR01']};
    await page.locator('#back-list').click();
    await page.locator('[data-id="999"]').click();
    await page.locator('#manual-decision').selectOption('COUNTER_OFFER');
    assert(await page.locator('#manual-amount').isEditable());
    assert.equal(await page.locator('#manual-amount').getAttribute('max'),'2000000');
    assert.equal(await page.locator('#manual-amount').getAttribute('min'),'500000');
    await page.locator('#manual-amount').fill('1500000');
    await page.locator('#manual-decision').selectOption('APPROVED');
    assert.equal(await page.locator('#manual-amount').inputValue(),'2000000');
    assert(await page.locator('#manual-amount').evaluate(el=>el.readOnly));
    await page.locator('#manual-decision').selectOption('COUNTER_OFFER');
    await page.locator('#manual-amount').fill('1500000');
    await page.locator('#manual-comment').fill('Synthetic counteroffer');
    await page.locator('#manual-form button').click();
    await page.waitForFunction(()=>!document.querySelector('#manual-form button')?.disabled);
    assert.equal(submitted.amount,1500000);assert.equal(submitted.decision,'COUNTER_OFFER');
